/**
 * The room's two alarms.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  WHY TWO, AND WHY THEY MUST NOT SOUND ALIKE
 *
 *  This room is told two completely different kinds of thing.
 *
 *    ATTENTION   the product noticed something. A threshold was crossed: the
 *                count has stalled, a state has gone quiet, a queue is
 *                backing up. Nobody is in danger. Somebody should look at a
 *                screen in the next few minutes.
 *
 *    SITUATION   a person standing in a field filed a report. An agent is
 *                being obstructed, a booth was closed early, there is a crowd.
 *                A human being is telling you something is wrong where they
 *                are standing, and the response is a telephone call, not a
 *                screen.
 *
 *  One sound for both means the room cannot tell, without looking, whether to
 *  walk to a monitor or pick up a phone. At two in the morning, on a wall
 *  display nobody is watching, that distinction is the entire value of having
 *  a sound at all.
 * ══════════════════════════════════════════════════════════════════════════
 *
 * ── WHY THESE ARE ALARMS AND NOT NOTIFICATION BEEPS ────────────────────────
 * The first version of this file played two pure tones with a soft rise and a
 * soft fall. It was polite, and polite is the one thing an alarm must never
 * be: it sat under the air conditioning, it sounded like a phone in somebody
 * else's pocket, and across a room with four people talking it was not there
 * at all. A sound a room has to strain to hear is a sound the room stops
 * relying on, and then the screen is back to being a red dot nobody sees.
 *
 * So both voices are built out of the four things that make a noise read as
 * an alarm rather than as a notification:
 *
 *   HARMONICS   a stack of detuned oscillators rather than one clean tone.
 *               A pure sine is a flute and is masked by conversation; a stack
 *               with its harmonics is a sounder and cuts through it.
 *   A FILTER    swept across the note, which is what gives a sounder its body
 *               and stops a stack sounding like a synthesiser.
 *   AN ENVELOPE that snaps on, holds flat, and cuts. A tone that fades in and
 *               out is a doorbell. A tone that holds is an alarm.
 *   MOVEMENT    a figure that goes somewhere and then comes back, several
 *               times over. A sound that sits still becomes part of the room
 *               within about four seconds.
 *
 * ── AND THE FIFTH THING, WHICH IS A TRAP ───────────────────────────────────
 * Drive — a soft clip, the distortion of a cheap horn driver pushed hard. It
 * is the obvious way to make a sound aggressive and it is mostly a mistake.
 * The situation voice was built that way first, as an emergency horn: a
 * sawtooth stack over a sub-octave, heavily clipped, with a nine-per-second
 * wobble. Everything about it was urgent on paper and it was simply unpleasant
 * to listen to — muddy rather than alarming, the sound of equipment breaking
 * rather than of equipment working. It was rejected on hearing, which is the
 * only way a sound can be judged.
 *
 * So the situation voice is now the cleanest thing in this file and carries on
 * its figure instead. Drive survives only on the attention voice, lightly, and
 * anything added here should be listened to before it is believed.
 *
 * ── HOW THEY ARE TOLD APART, ON FIVE AXES AT ONCE ──────────────────────────
 * Two alarms that differ only in pitch are two alarms a tired person confuses
 * within a week. These differ on everything a listener can use:
 *
 *                    ATTENTION                 SITUATION
 *   direction        rising, and stays up      an arch, up and back down
 *   register         high (1244→2093 Hz)       low (587→784 Hz)
 *   figure           two notes                 five
 *   timbre           driven, thin, hard        clean, round, undistorted
 *   rhythm           quick, even, mechanical   measured, melodic, deliberate
 *
 * Rising, bright and mechanical is a panel telling you a number moved. The
 * five-note arch is the shape a hospital monitor uses for its high-priority
 * alarm, and it is the shape it uses because it has to be heard all night by
 * people who must not be worn down by it — which is this room exactly. That
 * is not decoration: a room should not have to be trained, and should not
 * have to look.
 *
 * ── AND WHY THE SYNTHESIS IS HERE RATHER THAN IN A FILE ────────────────────
 * No audio assets. A room may be on a venue's wifi at nine at night behind a
 * proxy that has never heard of this product, and an alarm that depends on a
 * file finishing a download is an alarm that is silent exactly when the
 * network is bad — which correlates alarmingly well with when the night is
 * going badly. Everything below is generated by the browser's own oscillators
 * and cannot fail to load.
 */

/* --------------------------------------------------------------- the voices */

/**
 * The two voices, and the severities within each.
 *
 * The timbre fields are the voice: they are what a listener recognises, and
 * they never change between severities, because a louder version of the same
 * alarm is still recognisably that alarm. The `levels` are the figure played
 * in that voice — the notes as [frequency, seconds], how many times over, and
 * how loud.
 *
 *   partials  the oscillator stack, as [ratio of the fundamental, gain]. A
 *             ratio below 1 is a sub-octave, which is body rather than pitch.
 *   detune    cents of spread between the stack's two halves. A few cents of
 *             disagreement is what stops a stack sounding like a synthesiser.
 *   filter    a resonant sweep, as [type, from Hz, to Hz, Q]. The sweep runs
 *             across each note.
 *   drive     0 to 1, how hard the soft clip bites. 0 is no distortion at
 *             all, which is what a clean sounder wants; see the trap above.
 *   tremolo   [rate Hz, depth 0-1], the pulse. Depth 0.6 means the sound
 *             swings between 40% and 100% of its loudness, rate times a
 *             second.
 *   warble    cents of pitch wobble, several times a second. Kept as a plain
 *             number because it is also the flag for "this voice moves".
 *   glide     how much of a note is spent sliding into the pitch of the next
 *             one, as a fraction. 0 is a stepped two-tone, which is a
 *             doorbell. A third is a siren. A whole 1 never settles on a
 *             pitch at all, which is the wail of an air-raid siren.
 */
