/**
 * The "INEC Result Datas" account in Data Bank, and what is kept in it.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  AN ACCOUNT OF DATA BANK'S OWN KIND, NOT SOMETHING BESIDE IT
 *
 *  Data Bank keeps each body of work as an account: a row in
 *  `dumpsite.projects` and a vault, which is a schema named `bank_<name>`.
 *  Every table in a vault is listed in `dumpsite.datasets`, and that list is
 *  what Data Bank's own screens read. This opens the account the same way
 *  Data Bank's `ensureProject` does and lists every table it makes, so what
 *  is gathered from IReV shows on Data Bank's storage board under its
 *  account, readable and exportable there, with nothing new for Data Bank to
 *  learn.
 *
 *  ── ONE ACCOUNT, EVERY ELECTION ─────────────────────────────────────────
 *  Elections are rows, not tables. A presidential election in 2023 and a
 *  governorship in 2026 sit in the same five tables, told apart by the
 *  election they belong to, so moving between years and types is a filter
 *  and adding an election the portal publishes next year needs no change.
 * ══════════════════════════════════════════════════════════════════════════
 *
 * Every function takes `db`: a function `(text, params) => rows`. The caller
 * owns the connection, which keeps this file the same under a script, a
 * request and a test.
 */

