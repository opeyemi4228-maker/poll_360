/* ── A READ-THROUGH, DONE IN STEPS ──────────────────────────────────────── */

/** Begin reading an election through. Leaves one already under way alone. */
export async function startPass(db, electionId) {
  await db(
    `UPDATE ${V}.elections SET pass_started_at = now()
      WHERE election_id = $1 AND pass_started_at IS NULL`,
    [electionId]
  );
}

/** Wards of an election not yet read in the read-through under way. */
export async function wardsLeft(db, electionId, limit = null) {
  return db(
    `SELECT w.ward_id, w.ref, w.name
       FROM ${V}.wards w JOIN ${V}.elections e ON e.election_id = w.election_id
      WHERE w.election_id = $1 AND e.pass_started_at IS NOT NULL
        AND (w.read_at IS NULL OR w.read_at < e.pass_started_at)
      ORDER BY w.first DESC, w.read_at NULLS FIRST, w.ward_id
      LIMIT $2`,
    [electionId, limit]
  );
}

/* ── OUR OWN POLLING UNITS FIRST ────────────────────────────────────────────
   An election is read through ward by ward, and a nationwide one is 8,809
   wards. The only polling units there is anything to hold INEC's sheet
   against are the ones we filed a return from — a few hundred of them — and
   in ward order they could be reached at any point in a two-hour read-through.
   So they are named here, their wards are read before every other ward, and
   their sheets are examined and read before every other sheet. */

/** Name the polling units we hold returns for. Replaces the list held. */
export async function setWanted(db, electionId, codes) {
  const unique = [...new Set(codes.map((code) => String(code ?? "").trim()).filter(Boolean))];
  await db(`DELETE FROM ${V}.wanted WHERE election_id = $1 AND NOT (pu_code = ANY($2::text[]))`, [electionId, unique]);
  if (unique.length) {
    await db(
      `INSERT INTO ${V}.wanted (election_id, pu_code)
       SELECT $1, code FROM unnest($2::text[]) AS code
       ON CONFLICT DO NOTHING`,
      [electionId, unique]
    );
  }
  return unique.length;
}

/**
 * Mark the wards that hold a wanted unit, so they are read first.
 *
 * A ward's place in a unit's code is state/local government/ward, and the
 * portal files a ward under ids of its own. `states` joins the two: each
 * state's name as the portal spells it, with the two-digit number its codes
 * begin with.
 */
export async function prioritise(db, electionId, states) {
  await db(
    `UPDATE ${V}.wards w
        SET first = EXISTS (
          SELECT 1
            FROM ${V}.wanted x
            JOIN ${V}.lgas l ON l.election_id = w.election_id AND l.lga_id = w.lga_id
            JOIN unnest($2::text[], $3::text[]) AS st(name, number) ON st.name = l.state_name
           WHERE x.election_id = w.election_id
             AND left(x.pu_code, 8) = st.number || '/' || lpad(l.code, 2, '0') || '/' || lpad(w.code, 2, '0'))
      WHERE w.election_id = $1`,
    [electionId, states.map((state) => state.name), states.map((state) => state.number)]
  );
}

