/* ── ONE ELECTION, UNIT BY UNIT ─────────────────────────────────────────── */

/* ── WHAT CAN BE WRONG WITH A POLLING UNIT'S SHEET ──────────────────────────
   Said once, here, as the test the database applies, so the list of polling
   units, the totals by place and the verification screen can never count the
   same fault three different ways.

   Each is a fact about what INEC published, not a verdict on anybody. A sheet
   that went up four days late is late; why is for a person to find out.

   `day` is the placeholder holding polling day wherever one is needed. */

/** A sheet is called late from this many days after polling day. Counting at a
    collation centre runs through the night, so the day after is ordinary. */
export const LATE_DAYS = 2;

/** Days from polling day to the day a sheet went up, on a Lagos calendar. */
const daysAfter = (day) => `((s.uploaded_at AT TIME ZONE 'Africa/Lagos')::date - ${day}::date)`;

/** An address with no file in it: "https://storage.example/" and nothing after. */
const NO_FILE = "(s.sheet_url ~ '^https?://[^/]+/?$')";
const SOUND_READING = "r.status = 'read' AND r.balanced IS TRUE AND r.code_matches IS NOT FALSE";
const ODD = "(p.place_ok IS FALSE OR p.days_from_poll < 0 OR p.days_from_poll > 1)";

export const FAULTS = {
  /* A unit INEC itself lists as having no voters is not missing a sheet. */
  missing: () => "(s.sheet_url IS NULL AND NOT s.no_voters)",
  late: (day) => `(${daysAfter(day)} >= ${LATE_DAYS})`,
  replaced: () => "(s.earlier_sheets > 0)",
  /* Listed as up, and not there: the file has left the commission's storage,
     or the address the portal gives is the storage's front door with no file
     named in it at all. */
  gone: () => `(p.status = 'gone' OR r.status = 'gone' OR ${NO_FILE})`,
  unreadable: () => "(r.status = 'unreadable')",
  doubt: () => `(r.status = 'read' AND NOT (${SOUND_READING}))`,
  wrong_paper: () => "(r.status = 'read' AND r.code_matches IS FALSE)",
  overvote: () => `(${SOUND_READING} AND (r.valid_votes > r.accredited
                     OR (r.registered IS NOT NULL AND r.accredited > r.registered)))`,
  odd_picture: () => ODD,
};

/**
 * The faults that say something is wrong with a sheet itself. Not the ones
 * about publishing — a sheet that is absent, late, or listed with no file —
 * which run to tens of thousands and are counted and listed on their own.
 */
export const GRAVE = ["odd_picture", "wrong_paper", "overvote", "replaced"];

/** The faults by name, in the order they are counted and shown. */
export const FAULT_NAMES = Object.keys(FAULTS);

const SHOWN = {
  all: () => "true",
  up: () => "s.sheet_url IS NOT NULL",
  read: () => "r.status = 'read'",
  unread: () => "s.sheet_url IS NOT NULL AND r.unit_id IS NULL",
  flagged: FAULTS.odd_picture,
  ...FAULTS,
};

/** The views a list of polling units can be narrowed to. */
export const VIEWS = Object.keys(SHOWN);

/**
 * A page of an election's polling units, with what is held about each.
 *
 * `under` narrows it to a place by the start of the unit code ("05/16"), the
 * same way the verification screen names one. `heldOn` is polling day, which
 * "late" is measured from.
 */
export async function units(db, electionId, { show = "all", lga = null, q = null, under = null, heldOn = null, limit = 50, offset = 0 } = {}) {
  const where = `s.election_id = $1 AND ${(SHOWN[show] ?? SHOWN.all)("$5")}
    AND ($2::int IS NULL OR s.lga_id = $2)
    AND ($3::text IS NULL OR s.pu_code ILIKE $3 OR s.unit_name ILIKE $3)
    AND ($4::text IS NULL OR s.pu_code LIKE $4)
    AND ($5::date IS NULL OR true)`;
  const params = [electionId, lga, q ? `%${q}%` : null, under ? `${under}%` : null, heldOn];
  const from = `${V}.sheets s
       LEFT JOIN ${V}.readings r ON r.election_id = s.election_id AND r.unit_id = s.unit_id
       LEFT JOIN ${V}.pictures p ON p.election_id = s.election_id AND p.unit_id = s.unit_id`;

  const [rows, [total]] = await Promise.all([
    db(
      `SELECT s.unit_id, s.pu_code, s.unit_name, s.sheet_url, s.sheet_at, s.earlier_sheets,
              s.uploaded_at, s.no_voters, ${daysAfter("$5")} AS days_after,
              l.name AS lga_name, w.name AS ward_name,
              r.status AS read_status, r.balanced, r.code_matches, r.accredited, r.valid_votes, r.party_votes,
              p.status AS picture_status, p.device_model, p.taken_at, p.stored_at, p.taken_lga, p.taken_state,
              p.place_ok, p.days_from_poll, p.latitude
         FROM ${from}
         LEFT JOIN ${V}.lgas l ON l.election_id = s.election_id AND l.lga_id = s.lga_id
         LEFT JOIN ${V}.wards w ON w.election_id = s.election_id AND w.ward_id = s.ward_id
        WHERE ${where}
        ORDER BY s.pu_code
        LIMIT ${Number(limit) || 50} OFFSET ${Number(offset) || 0}`,
      params
    ),
    db(`SELECT count(*)::int AS n FROM ${from} WHERE ${where}`, params),
  ]);

  return { rows, total: total?.n ?? 0 };
}

