/* ── ONE ELECTION, ADDED UP BY PLACE ────────────────────────────────────────
   A polling unit's code is its address: state/local government/ward/unit. So
   "every unit in Bauchi" is every code beginning 05, and adding up by place
   is grouping by how much of the code is kept — two characters for a state,
   five for a local government, eight for a ward, all of it for a unit. The
   same codes Poll360's own returns are filed under, which is what lets the
   two be held side by side without a table to translate between them. */

/** A reading that can be relied on: it adds up, and it is this unit's paper. */
const SOUND = SOUND_READING;

/**
 * Everything under one place, grouped one step down.
 *
 * `under` is the code so far ("" for the country, "05", "05/16", "05/16/01")
 * and `width` how much of each unit's code names the next step. `heldOn` is
 * polling day. Every fault in FAULTS comes back as a count under its own name.
 */
export async function placeTotals(db, electionId, under, width, heldOn = null) {
  return db(
    `SELECT left(s.pu_code, $2) AS key,
            min(l.name) AS lga_name, min(w.name) AS ward_name,
            min(s.unit_name) AS unit_name, min(s.unit_id) AS unit_id,
            count(*)::int AS units,
            count(s.sheet_url)::int AS sheets,
            count(*) FILTER (WHERE s.no_voters)::int AS no_voters,
            count(s.uploaded_at)::int AS timed,
            count(*) FILTER (WHERE r.status = 'read')::int AS read,
            count(*) FILTER (WHERE ${SOUND})::int AS sound,
            count(*) FILTER (WHERE ${FAULT_NAMES.map((name) => FAULTS[name]("$4")).join(" OR ")})::int AS faulty,
            ${FAULT_NAMES.map((name) => `count(*) FILTER (WHERE ${FAULTS[name]("$4")})::int AS ${name}`).join(",\n            ")},
            coalesce(sum(r.registered) FILTER (WHERE ${SOUND}), 0)::int AS registered,
            coalesce(sum(r.accredited) FILTER (WHERE ${SOUND}), 0)::int AS accredited,
            coalesce(sum(r.rejected) FILTER (WHERE ${SOUND}), 0)::int AS rejected,
            coalesce(sum(r.valid_votes) FILTER (WHERE ${SOUND}), 0)::int AS valid
       FROM ${V}.sheets s
       LEFT JOIN ${V}.readings r ON r.election_id = s.election_id AND r.unit_id = s.unit_id
       LEFT JOIN ${V}.pictures p ON p.election_id = s.election_id AND p.unit_id = s.unit_id
       LEFT JOIN ${V}.lgas l ON l.election_id = s.election_id AND l.lga_id = s.lga_id
       LEFT JOIN ${V}.wards w ON w.election_id = s.election_id AND w.ward_id = s.ward_id
      WHERE s.election_id = $1 AND s.pu_code LIKE $3
      GROUP BY 1
      ORDER BY 1`,
    [electionId, width, `${under}%`, heldOn]
  );
}

/** What a place is called, from any one polling unit under it. */
export async function placeName(db, electionId, under) {
  const [row] = await db(
    `SELECT l.name AS lga_name, w.name AS ward_name
       FROM ${V}.sheets s
       LEFT JOIN ${V}.lgas l ON l.election_id = s.election_id AND l.lga_id = s.lga_id
       LEFT JOIN ${V}.wards w ON w.election_id = s.election_id AND w.ward_id = s.ward_id
      WHERE s.election_id = $1 AND s.pu_code LIKE $2
      LIMIT 1`,
    [electionId, `${under}%`]
  );
  return row ?? null;
}

/**
 * How many sheets under a place went up on each day, counted from polling
 * day: 0 is the day itself, 1 the day after. Only sheets whose file carries
 * the time; see `uploadedAt` in ./shape.js.
 */
export async function uploadDays(db, electionId, under, heldOn) {
  if (!heldOn) return [];
  return db(
    `SELECT ${daysAfter("$3")} AS day, count(*)::int AS sheets
       FROM ${V}.sheets s
      WHERE s.election_id = $1 AND s.pu_code LIKE $2 AND s.uploaded_at IS NOT NULL
      GROUP BY 1
      ORDER BY 1`,
    [electionId, `${under}%`, heldOn]
  );
}

/** Every party's votes under one place, grouped one step down, from sound readings only. */
export async function placeVotes(db, electionId, under, width) {
  return db(
    `SELECT left(r.pu_code, $2) AS key, v.key AS party, sum(v.value::int)::int AS votes
       FROM ${V}.readings r, jsonb_each_text(r.party_votes) v
      WHERE r.election_id = $1 AND r.pu_code LIKE $3 AND ${SOUND}
        AND v.value ~ '^[0-9]+$'
      GROUP BY 1, 2`,
    [electionId, width, `${under}%`]
  );
}

/**
 * The polling units under one place that carry a fault, with what it is.
 *
 * `kind` is one fault from FAULTS, or "any" for every one of them. Without
 * it the list is the grave ones only — a paper that is wrong, figures that
 * cannot be, a sheet replaced or gone — and not the tens of thousands that
 * are merely missing or late, which would bury them. The gravest first, and
 * no more than `limit`: this is a list for a person to work down.
 */
export async function placeFlags(db, electionId, under, { kind = null, heldOn = null, limit = 60 } = {}) {
  const names = FAULTS[kind] ? [kind] : kind === "any" ? FAULT_NAMES : GRAVE;
  const which = names.map((name) => FAULTS[name]("$3")).join("\n             OR ");
  return db(
    `SELECT s.unit_id, s.pu_code, s.unit_name, s.earlier_sheets, s.uploaded_at, s.no_voters,
            (s.sheet_url IS NOT NULL) AS sheet_up, ${daysAfter("$3")} AS days_after,
            ${NO_FILE} AS no_file,
            l.name AS lga_name, l.state_name, w.name AS ward_name,
            p.status AS picture_status, p.place_ok, p.days_from_poll, p.taken_lga, p.taken_state,
            r.status AS read_status, r.balanced, r.problems,
            r.code_matches, r.code_on_sheet, r.accredited, r.valid_votes, r.registered,
            (${SOUND}) AS sound
       FROM ${V}.sheets s
       LEFT JOIN ${V}.readings r ON r.election_id = s.election_id AND r.unit_id = s.unit_id
       LEFT JOIN ${V}.pictures p ON p.election_id = s.election_id AND p.unit_id = s.unit_id
       LEFT JOIN ${V}.lgas l ON l.election_id = s.election_id AND l.lga_id = s.lga_id
       LEFT JOIN ${V}.wards w ON w.election_id = s.election_id AND w.ward_id = s.ward_id
      WHERE s.election_id = $1 AND s.pu_code LIKE $2
        AND (${which})
      ORDER BY (p.place_ok IS FALSE) DESC, (r.code_matches IS FALSE) DESC,
               ${FAULTS.overvote()} DESC NULLS LAST, s.earlier_sheets DESC,
               ${FAULTS.gone()} DESC NULLS LAST,
               ${daysAfter("$3")} DESC NULLS LAST, s.pu_code
      LIMIT $4`,
    [electionId, `${under}%`, heldOn, limit]
  );
}

/** What is held for the polling units named, for holding against our own returns of them. */
export async function unitsByCode(db, electionId, codes) {
  if (!codes.length) return [];
  return db(
    `SELECT s.unit_id, s.pu_code, s.unit_name, (s.sheet_url IS NOT NULL) AS sheet_up,
            r.status, r.balanced, r.code_matches, r.registered, r.accredited, r.rejected, r.party_votes
       FROM ${V}.sheets s
       LEFT JOIN ${V}.readings r ON r.election_id = s.election_id AND r.unit_id = s.unit_id
      WHERE s.election_id = $1 AND s.pu_code = ANY($2::text[])`,
    [electionId, codes]
  );
}

/** The figures read for an election, for holding against our own returns. */
export async function readings(db, electionId) {
  return db(
    `SELECT unit_id, pu_code, status, balanced, code_matches, registered, accredited, rejected, party_votes
       FROM ${V}.readings WHERE election_id = $1 AND status = 'read'`,
    [electionId]
  );
}

export async function linkProject(db, electionId, projectId) {
  await db(`UPDATE ${V}.elections SET project_id = $2 WHERE election_id = $1`, [electionId, projectId]);
}

/** The gathered election a Poll360 project is compared with, if one was chosen. */
export async function electionForProject(db, projectId) {
  const [row] = await db(
    `SELECT e.*, to_char(e.held_on, 'YYYY-MM-DD') AS held_on
       FROM ${V}.elections e WHERE e.project_id = $1 ORDER BY e.held_on DESC LIMIT 1`,
    [projectId]
  );
  return row ?? null;
}

/**
 * Bring Data Bank's own figures up to date: the row count it shows for each
 * table, and what the source has paid in.
 */
export async function settle(db) {
  for (const table of Object.keys(TABLES)) {
    await db(
      `UPDATE dumpsite.datasets SET rows = (SELECT count(*) FROM ${V}.${table})
        WHERE table_schema = $1 AND table_name = $2`,
      [V, table]
    );
  }
  await db(
    `UPDATE dumpsite.connections
        SET last_sync_at = now(), status = 'LINKED', last_error = NULL,
            records = (SELECT count(*) FROM ${V}.sheets)
      WHERE name = 'INEC IReV'
        AND project_id = (SELECT id FROM dumpsite.projects WHERE tenant_id = 'default' AND slug = $1)`,
    [ACCOUNT.slug]
  );
}

/** How much room the account is taking. */
export async function weight(db) {
  const [row] = await db(
    `SELECT coalesce(sum(pg_total_relation_size(c.oid)), 0)::bigint AS bytes
       FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = $1 AND c.relkind = 'r'`,
    [V]
  );
  return Number(row?.bytes ?? 0);
}
