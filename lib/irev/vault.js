/* ── ONE GATHERER AT A TIME ─────────────────────────────────────────────── */

/**
 * Take the turn, or learn that somebody else has it.
 *
 * The screen left open in two windows, the command running on a machine and
 * a server answering a health check may all try to gather at once. A row with
 * an expiry settles it: whoever moves the expiry forward has the turn, and a
 * holder that dies simply stops renewing it. A session lock would be tidier
 * and does not survive a pooled connection.
 */
export async function takeTurn(db, seconds = 120) {
  await db(`INSERT INTO ${V}.state (name, at) VALUES ('turn', 'epoch') ON CONFLICT (name) DO NOTHING`);
  const taken = await db(
    `UPDATE ${V}.state SET at = now() + make_interval(secs => $1)
      WHERE name = 'turn' AND at < now() RETURNING name`,
    [seconds]
  );
  return taken.length === 1;
}

export async function endTurn(db) {
  await db(`UPDATE ${V}.state SET at = 'epoch' WHERE name = 'turn'`);
}

export async function mark(db, name, value = null) {
  await db(
    `INSERT INTO ${V}.state (name, value, at) VALUES ($1, $2, now())
     ON CONFLICT (name) DO UPDATE SET value = EXCLUDED.value, at = now()`,
    [name, value]
  );
}

/** Seconds since something was last marked, or null where it never was. */
export async function since(db, name) {
  const [row] = await db(
    `SELECT extract(epoch FROM now() - at)::int AS seconds, value FROM ${V}.state WHERE name = $1`,
    [name]
  );
  return row ?? null;
}

/* ── THE FIGURES READ OFF THE SHEETS ────────────────────────────────────── */

/**
 * Sheets with nothing read from them yet: never read, replaced since, or
 * failed fewer than three times. Newest uploads first, so on the night the
 * figures follow the sheets.
 */
export async function sheetsToRead(db, electionId, limit) {
  return db(
    `SELECT s.election_id, s.unit_id, s.pu_code, s.sheet_url, coalesce(r.attempts, 0) AS attempts
       FROM ${V}.sheets s
       LEFT JOIN ${V}.readings r ON r.election_id = s.election_id AND r.unit_id = s.unit_id
      WHERE s.election_id = $1 AND s.sheet_url IS NOT NULL
        AND (r.unit_id IS NULL OR r.sheet_url IS DISTINCT FROM s.sheet_url
             OR (r.status = 'failed' AND r.attempts < 6))
      ORDER BY EXISTS (SELECT 1 FROM ${V}.wanted x
                        WHERE x.election_id = s.election_id AND x.pu_code = s.pu_code) DESC,
               /* One that failed goes to the back, so a sheet the storage will not
                  hand over cannot hold up every sheet behind it. */
               coalesce(r.attempts, 0),
               s.sheet_at DESC NULLS LAST
      LIMIT $2`,
    [electionId, limit]
  );
}

