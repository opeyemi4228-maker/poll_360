/* ── READING BACK ───────────────────────────────────────────────────────── */

export async function elections(db) {
  return db(
    `SELECT e.*, to_char(e.held_on, 'YYYY-MM-DD') AS held_on,
            coalesce(s.units, 0) AS units_held, coalesce(s.sheets, 0) AS sheets_held,
            coalesce(w.wards, 0) AS wards, coalesce(w.wards_left, 0) AS wards_left,
            coalesce(r.figures, 0) AS figures_read, coalesce(r.balanced, 0) AS figures_balanced,
            coalesce(p.examined, 0) AS pictures_examined
       FROM ${V}.elections e
       LEFT JOIN (SELECT election_id, count(*)::int AS units, count(sheet_url)::int AS sheets
                    FROM ${V}.sheets GROUP BY 1) s USING (election_id)
       LEFT JOIN (SELECT w.election_id, count(*)::int AS wards,
                         count(*) FILTER (WHERE x.pass_started_at IS NOT NULL
                           AND (w.read_at IS NULL OR w.read_at < x.pass_started_at))::int AS wards_left
                    FROM ${V}.wards w JOIN ${V}.elections x USING (election_id) GROUP BY 1) w USING (election_id)
       LEFT JOIN (SELECT election_id, count(*) FILTER (WHERE status = 'read')::int AS figures,
                         count(*) FILTER (WHERE balanced)::int AS balanced
                    FROM ${V}.readings GROUP BY 1) r USING (election_id)
       LEFT JOIN (SELECT election_id, count(*)::int AS examined
                    FROM ${V}.pictures GROUP BY 1) p USING (election_id)
      ORDER BY e.held_on DESC NULLS LAST, e.name`
  );
}

