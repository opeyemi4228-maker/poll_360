/** The statement that creates one table. */
export function createStatement(table) {
  const spec = TABLES[table];
  const columns = spec.columns.map(([name, type, rest]) => `${name} ${type}${rest ? ` ${rest}` : ""}`);
  const key = spec.key ? `, PRIMARY KEY (${spec.key})` : "";
  return `CREATE TABLE IF NOT EXISTS ${V}.${table} (${ROW}, ${columns.join(", ")}${key})`;
}

/**
 * Open the account and everything in it. Safe to run every time: each step
 * leaves what is already there alone.
 */
export async function open(db) {
  const hub = await db(`SELECT to_regclass('dumpsite.projects') AS projects`);
  if (!hub[0]?.projects) {
    throw new Error(
      "This database has no Data Bank in it. Point DATABANK_DATABASE_URL at Data Bank's database."
    );
  }

  await db(`CREATE SCHEMA IF NOT EXISTS ${V}`);

  /* The same insert Data Bank's own ensureProject makes. */
  await db(
    `INSERT INTO dumpsite.projects (tenant_id, name, slug, schema_name, purpose, created_by)
     VALUES ('default', $1, $2, $3, $4, $5)
     ON CONFLICT (tenant_id, slug) DO NOTHING`,
    [ACCOUNT.name, ACCOUNT.slug, V, ACCOUNT.purpose, ACTOR]
  );
  const [account] = await db(
    `SELECT id, name, schema_name, created_at FROM dumpsite.projects
      WHERE tenant_id = 'default' AND slug = $1`,
    [ACCOUNT.slug]
  );

  for (const table of Object.keys(TABLES)) {
    await db(createStatement(table));
  }
  await db(`CREATE INDEX IF NOT EXISTS sheets_code_idx ON ${V}.sheets (election_id, pu_code)`);
  await db(`CREATE INDEX IF NOT EXISTS sheets_changed_idx ON ${V}.sheets (election_id, changed_at DESC)`);
  await db(`CREATE INDEX IF NOT EXISTS wards_read_idx ON ${V}.wards (election_id, read_at NULLS FIRST)`);
  await db(`CREATE UNIQUE INDEX IF NOT EXISTS follows_key ON ${V}.follows
              (coalesce(year, 0), coalesce(type_code, ''), coalesce(state_name, ''))`);

  /* Columns added since an account was first opened. Additive only, as
     everything in Data Bank is. */
  await db(`ALTER TABLE ${V}.elections ADD COLUMN IF NOT EXISTS project_id text`);
  await db(`ALTER TABLE ${V}.pictures ADD COLUMN IF NOT EXISTS stored_at timestamptz`);
  await db(`ALTER TABLE ${V}.wards ADD COLUMN IF NOT EXISTS first boolean NOT NULL DEFAULT false`);
  await db(`ALTER TABLE ${V}.sheets ADD COLUMN IF NOT EXISTS uploaded_at timestamptz`);
  await stampUploads(db);
  /* Coming up from an earlier version only: sheets examined before the time
     the commission received them was recorded are looked at once more, and
     readings that failed on a document the reader can now open are retried. */
  const before = Number((await since(db, "schema"))?.value ?? SCHEMA);
  if (before < 4) {
    await db(`DELETE FROM ${V}.pictures WHERE stored_at IS NULL AND status <> 'gone'`);
    await db(`DELETE FROM ${V}.readings WHERE status = 'failed'`);
  }
  await db(`CREATE INDEX IF NOT EXISTS pictures_spot_idx ON ${V}.pictures (election_id, latitude, longitude)`);
  /* "Every code beginning 05/16" is a search by the start of a text, which an
     ordinary index does not serve. These two do. */
  await db(`CREATE INDEX IF NOT EXISTS sheets_place_idx ON ${V}.sheets (election_id, pu_code text_pattern_ops)`);
  await db(`CREATE INDEX IF NOT EXISTS readings_place_idx ON ${V}.readings (election_id, pu_code text_pattern_ops)`);

  /* List each table on Data Bank's board, once. */
  for (const [table, spec] of Object.entries(TABLES)) {
    const columns = spec.columns.map(([name, type]) => ({ source: name, name, type }));
    await db(
      `INSERT INTO dumpsite.datasets
         (tenant_id, project_id, name, kind, table_schema, table_name, columns, rows, created_by)
       SELECT 'default', $1, $2, 'REST_API', $3, $4, $5::jsonb, 0, $6
        WHERE NOT EXISTS (
          SELECT 1 FROM dumpsite.datasets WHERE table_schema = $3 AND table_name = $4
        )`,
      [account.id, spec.label, V, table, JSON.stringify(columns), ACTOR]
    );
    await db(`UPDATE dumpsite.datasets SET columns = $3::jsonb WHERE table_schema = $1 AND table_name = $2`, [
      V,
      table,
      JSON.stringify(columns),
    ]);
  }

  /* And the portal as a source on the paying-in counter. */
  await db(
    `INSERT INTO dumpsite.connections (tenant_id, project_id, kind, name, endpoint, resource, created_by)
     SELECT 'default', $1, 'REST_API', 'INEC IReV', $2, 'election-types', $3
      WHERE NOT EXISTS (
        SELECT 1 FROM dumpsite.connections WHERE project_id = $1 AND name = 'INEC IReV'
      )`,
    [account.id, "https://www.inecelectionresults.ng/", ACTOR]
  );

  await mark(db, "schema", SCHEMA);
  return account;
}

/**
 * Give every sheet held the time in its own file name, where it has one and
 * it has not been taken yet. The same rule as `uploadedAt` in ./shape.js,
 * said to the database, for sheets gathered before the time was kept.
 */
export async function stampUploads(db, electionId = null) {
  /* The file's name, and the first ten digits standing alone in it. 15 to 19
     at the front keeps it to 2017–2033 before the range below is applied. */
  const stamp = `to_timestamp(substring(regexp_replace(split_part(sheet_url, '?', 1), '^.*/', '')
                   from '(?:^|[^0-9])(1[5-9][0-9]{8})(?:[^0-9]|$)')::bigint)`;
  await db(
    `UPDATE ${V}.sheets
        SET uploaded_at = ${stamp}
      WHERE uploaded_at IS NULL AND sheet_url IS NOT NULL
        AND ($1::int IS NULL OR election_id = $1)
        AND ${stamp} BETWEEN timestamptz '2019-01-01' AND now() + interval '1 day'`,
    [electionId]
  );
}

/* ── WRITING ──────────────────────────────────────────────────────────────
   Every write sends whole columns as arrays and lets the database unnest
   them, so a ward of forty units is one statement rather than forty. */

const column = (rows, name) => rows.map((row) => row[name] ?? null);

export async function saveTypes(db, rows) {
  if (!rows.length) return;
  await db(
    `INSERT INTO ${V}.election_types (code, name, type_id, ref)
     SELECT * FROM unnest($1::text[], $2::text[], $3::int[], $4::text[])
     ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, type_id = EXCLUDED.type_id, ref = EXCLUDED.ref`,
    ["code", "name", "type_id", "ref"].map((name) => column(rows, name))
  );
}

export async function saveElections(db, rows) {
  if (!rows.length) return;
  await db(
    `INSERT INTO ${V}.elections
       (election_id, ref, type_code, type_name, year, held_on, name, state_id, state_name, area_name, area_kind)
     SELECT * FROM unnest($1::int[], $2::text[], $3::text[], $4::text[], $5::int[], $6::date[],
                          $7::text[], $8::int[], $9::text[], $10::text[], $11::text[])
     ON CONFLICT (election_id) DO UPDATE SET
       ref = EXCLUDED.ref, type_code = EXCLUDED.type_code, type_name = EXCLUDED.type_name,
       year = EXCLUDED.year, held_on = EXCLUDED.held_on, name = EXCLUDED.name,
       state_id = EXCLUDED.state_id, state_name = EXCLUDED.state_name,
       area_name = EXCLUDED.area_name, area_kind = EXCLUDED.area_kind`,
    [
      "election_id", "ref", "type_code", "type_name", "year", "held_on",
      "name", "state_id", "state_name", "area_name", "area_kind",
    ].map((name) => column(rows, name))
  );
}

export async function savePlaces(db, { lgas, wards }) {
  if (lgas.length) {
    await db(
      `INSERT INTO ${V}.lgas (election_id, lga_id, ref, name, code, state_id, state_name)
       SELECT * FROM unnest($1::int[], $2::int[], $3::text[], $4::text[], $5::text[], $6::int[], $7::text[])
       ON CONFLICT (election_id, lga_id) DO UPDATE SET
         ref = EXCLUDED.ref, name = EXCLUDED.name, code = EXCLUDED.code,
         state_id = EXCLUDED.state_id, state_name = EXCLUDED.state_name`,
      ["election_id", "lga_id", "ref", "name", "code", "state_id", "state_name"].map((name) => column(lgas, name))
    );
  }

  /* Wards go in a few thousand at a time: a nationwide election has 8,809. */
  for (let at = 0; at < wards.length; at += 2000) {
    const slice = wards.slice(at, at + 2000);
    await db(
      `INSERT INTO ${V}.wards (election_id, ward_id, ref, name, code, lga_id, state_id)
       SELECT * FROM unnest($1::int[], $2::int[], $3::text[], $4::text[], $5::text[], $6::int[], $7::int[])
       ON CONFLICT (election_id, ward_id) DO UPDATE SET
         ref = EXCLUDED.ref, name = EXCLUDED.name, code = EXCLUDED.code,
         lga_id = EXCLUDED.lga_id, state_id = EXCLUDED.state_id`,
      ["election_id", "ward_id", "ref", "name", "code", "lga_id", "state_id"].map((name) => column(slice, name))
    );
  }
}

/**
 * Save polling units and their sheets, and say what was new.
 *
 * A row is written only where something about the sheet differs from what is
 * held, so reading the same ward twice changes nothing and `changed_at` means
 * what it says. Returns how many units were new to the vault and how many
 * sheets went up or were replaced.
 */
export async function saveSheets(db, rows) {
  if (!rows.length) return { units: 0, sheets: 0 };

  const written = await db(
    `INSERT INTO ${V}.sheets AS held
       (election_id, unit_id, pu_code, unit_name, ward_id, lga_id, state_id,
        sheet_url, sheet_at, supplement, earlier_sheets, no_voters, uploaded_at)
     SELECT * FROM unnest($1::int[], $2::int[], $3::text[], $4::text[], $5::int[], $6::int[], $7::int[],
                          $8::text[], $9::timestamptz[], $10::boolean[], $11::int[], $12::boolean[],
                          $13::timestamptz[])
     ON CONFLICT (election_id, unit_id) DO UPDATE SET
       pu_code = EXCLUDED.pu_code, unit_name = EXCLUDED.unit_name,
       ward_id = COALESCE(EXCLUDED.ward_id, held.ward_id),
       lga_id = COALESCE(EXCLUDED.lga_id, held.lga_id),
       state_id = COALESCE(EXCLUDED.state_id, held.state_id),
       sheet_url = EXCLUDED.sheet_url, sheet_at = EXCLUDED.sheet_at,
       supplement = EXCLUDED.supplement, earlier_sheets = EXCLUDED.earlier_sheets,
       no_voters = EXCLUDED.no_voters, uploaded_at = EXCLUDED.uploaded_at, changed_at = now()
     WHERE (held.sheet_url, held.sheet_at, held.earlier_sheets)
           IS DISTINCT FROM (EXCLUDED.sheet_url, EXCLUDED.sheet_at, EXCLUDED.earlier_sheets)
     RETURNING (xmax = 0) AS fresh, sheet_url IS NOT NULL AS up`,
    [
      "election_id", "unit_id", "pu_code", "unit_name", "ward_id", "lga_id", "state_id",
      "sheet_url", "sheet_at", "supplement", "earlier_sheets", "no_voters", "uploaded_at",
    ].map((name) => column(rows, name))
  );

  return {
    units: written.filter((row) => row.fresh).length,
    sheets: written.filter((row) => row.up).length,
  };
}

/** Mark one ward read, with what was found in it. */
