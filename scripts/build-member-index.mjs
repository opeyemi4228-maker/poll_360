/**
 * The eager half of the membership split.
 *
 *   node scripts/build-member-index.mjs
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  WHAT THIS FILE EXISTS TO KEEP OUT OF THE BUNDLE
 *
 *  The imported ADC registers come to about eight megabytes of counts across
 *  the states imported so far, and lib/members.js is reached from a client
 *  component — so without a split, every one of those bytes is downloaded by
 *  every person who opens the dashboard, including the majority who look at
 *  the map and never open a ward.
 *
 *  The index is what the map draws: states and local governments, with a
 *  count, a gender split and an age split each. The wards and polling units —
 *  which are the overwhelming majority of the bytes — stay in the per-state
 *  files and are fetched when somebody opens that state.
 *
 *  ── SO THE ONE RULE HERE IS: NO WARDS ────────────────────────────────────
 *  Every local government is copied without its `wards` key. That omission is
 *  load-bearing twice over: it is the whole size saving, and lib/members.js
 *  reads the absence of `wards` as "this state's detail is not fetched yet"
 *  and returns null rather than nought. A ward drawn at nought because its
 *  file is still in flight is a ward a campaign writes off.
 * ══════════════════════════════════════════════════════════════════════════
 *
 * ── STATES THAT HAVE NOT BEEN IMPORTED ARE ABSENT, NOT EMPTY ───────────────
 * Only the registers actually present on disk are indexed. A state with no
 * register does not appear in the index at all, which is what makes
 * `membersAt` return null for it — the module's existing answer for "unknown".
 * Writing it in with nought members would draw a state where the ADC has no
 * members, which is a claim nobody has made.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const DIR = "lib/data";
const OUT = `${DIR}/members-adc-index.js`;

const files = readdirSync(DIR)
  .filter((name) => /^members-[a-z]{3}-adc\.js$/.test(name))
  .sort();

if (files.length === 0) {
  console.error(`No member registers in ${DIR}. Run scripts/import-register.py first.`);
  process.exit(1);
}

const states = {};
let members = 0;
let lgas = 0;
let wards = 0;
let units = 0;

for (const file of files) {
  const { [Object.keys(await import(`../${DIR}/${file}`))[0]]: register } = await import(
    `../${DIR}/${file}`
  );

  const code = register.stateCode;
  if (!code) {
    console.error(`${file} carries no stateCode. Re-run the importer for it.`);
    process.exit(1);
  }

  /* Every local government, without its wards. Copied field by field rather
     than by deleting a key off a shared object, because these modules are
     imported live here and mutating one would corrupt the detail file this
     same script has just read. */
  const indexed = {};
  for (const [name, lga] of Object.entries(register.lgas ?? {})) {
    indexed[name] = {
      members: lga.members ?? 0,
      gender: lga.gender ?? {},
      ages: lga.ages ?? {},
    };
  }

  states[code] = {
    state: register.state,
    stateCode: code,
    party: register.party,
    members: register.members ?? 0,
    counts: register.counts ?? {},
    quality: register.quality ?? {},
    lgas: indexed,
  };

  members += register.members ?? 0;
  lgas += register.counts?.lgas ?? 0;
  wards += register.counts?.wards ?? 0;
  units += register.counts?.units ?? 0;
}

const codes = Object.keys(states).sort();

const body = `/**
 * ADC membership across every state imported so far, to local government.
 *
 * Generated by scripts/build-member-index.mjs. Edit the script, not this file.
 *
 * NO PERSONAL DATA. The registers this is built from carry names, ages,
 * telephone numbers and National Identification Numbers. None of them are
 * here, or in the per-state files. Counts only.
 *
 * ── WARDS AND POLLING UNITS ARE DELIBERATELY NOT HERE ──────────────────────
 * They live in lib/data/members-<code>-adc.js and are fetched when somebody
 * opens that state. lib/members.js reads a local government with no \`wards\`
 * key as "detail not fetched yet" and answers null rather than nought.
 *
 * ── AND ${37 - codes.length} STATES ARE NOT HERE AT ALL ─────────────────────────────────
 * ${codes.length} of Nigeria's 37 registers have been imported. A state that is absent is
 * unknown, not empty — the ADC has not published a register this product has
 * read, and drawing it at nought would be a claim nobody has made.
 *
 * Members: ${members.toLocaleString("en-NG")}
 * States:  ${codes.length}  ·  ${codes.join(" ")}
 */

export const ADC_INDEX = ${JSON.stringify({
  party: "ADC",
  counts: { states: codes.length, lgas, wards, units, members },
  states,
})};
`;

writeFileSync(OUT, body);

console.log(
  `${OUT}\n  ${codes.length} states · ${members.toLocaleString("en-NG")} members · ` +
    `${lgas} LGAs · ${wards.toLocaleString("en-NG")} wards · ${units.toLocaleString("en-NG")} units`
);
